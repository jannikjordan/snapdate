#Requires -Version 7.4
<#
.SYNOPSIS
    Regenerates Strings.resx, Strings.de.resx and LocalizedStrings.cs from strings.tsv.

.DESCRIPTION
    src/Snapdate.App/Localization/strings.tsv is the single source of truth for UI text:
    one line per key, tab-separated: Key <TAB> English <TAB> German.
    Strings that are used with string.Format must escape literal braces as {{ and }}.

.EXAMPLE
    pwsh scripts/dev/Update-Strings.ps1
#>
Set-StrictMode -Version Latest
$ErrorActionPreference = 'Stop'

$dir = Join-Path $PSScriptRoot '..' '..' 'src' 'Snapdate.App' 'Localization'
$rows = Get-Content (Join-Path $dir 'strings.tsv') -Encoding utf8 |
    Where-Object { $_.Trim() -ne '' } |
    ForEach-Object {
        $parts = $_ -split "`t"
        if ($parts.Count -ne 3) { throw "Expected 3 tab-separated columns: $_" }
        [pscustomobject]@{ Key = $parts[0]; En = $parts[1]; De = $parts[2] }
    }

$dupes = $rows | Group-Object Key | Where-Object Count -gt 1
if ($dupes) { throw "Duplicate keys: $($dupes.Name -join ', ')" }

$header = @'
<?xml version="1.0" encoding="utf-8"?>
<root>
  <resheader name="resmimetype"><value>text/microsoft-resx</value></resheader>
  <resheader name="version"><value>2.0</value></resheader>
  <resheader name="reader"><value>System.Resources.ResXResourceReader, System.Windows.Forms, Version=4.0.0.0, Culture=neutral, PublicKeyToken=b77a5c561934e089</value></resheader>
  <resheader name="writer"><value>System.Resources.ResXResourceWriter, System.Windows.Forms, Version=4.0.0.0, Culture=neutral, PublicKeyToken=b77a5c561934e089</value></resheader>
'@

function Write-Resx([string] $path, [string] $column) {
    $lines = [System.Collections.Generic.List[string]]::new()
    $lines.Add($header.TrimEnd())
    foreach ($row in $rows) {
        $value = [System.Security.SecurityElement]::Escape($row.$column)
        $lines.Add("  <data name=`"$($row.Key)`" xml:space=`"preserve`"><value>$value</value></data>")
    }
    $lines.Add('</root>')
    [IO.File]::WriteAllText($path, ($lines -join "`n") + "`n", [Text.UTF8Encoding]::new($false))
}

Write-Resx (Join-Path $dir 'Strings.resx') 'En'
Write-Resx (Join-Path $dir 'Strings.de.resx') 'De'

$cs = [System.Text.StringBuilder]::new()
[void] $cs.AppendLine('// <auto-generated> by scripts/dev/Update-Strings.ps1 from strings.tsv. Do not edit by hand.')
[void] $cs.AppendLine('#nullable enable')
[void] $cs.AppendLine('using System.Globalization;')
[void] $cs.AppendLine('using System.Resources;')
[void] $cs.AppendLine('')
[void] $cs.AppendLine('namespace Snapdate.App.Localization;')
[void] $cs.AppendLine('')
[void] $cs.AppendLine('/// <summary>Strongly typed, AOT-safe access to UI strings for one culture.</summary>')
[void] $cs.AppendLine('public sealed class LocalizedStrings(CultureInfo culture)')
[void] $cs.AppendLine('{')
[void] $cs.AppendLine('    private static readonly ResourceManager Resources =')
[void] $cs.AppendLine('        new("Snapdate.App.Localization.Strings", typeof(LocalizedStrings).Assembly);')
[void] $cs.AppendLine('')
[void] $cs.AppendLine('    /// <summary>Culture the strings are resolved for.</summary>')
[void] $cs.AppendLine('    public CultureInfo Culture { get; } = culture;')
foreach ($row in $rows) {
    [void] $cs.AppendLine('')
    [void] $cs.AppendLine("    public string $($row.Key) => Get(nameof($($row.Key)));")
}
[void] $cs.AppendLine('')
[void] $cs.AppendLine('    /// <summary>Looks up a key; falls back to the key itself so missing strings are visible, not fatal.</summary>')
[void] $cs.AppendLine('    public string Get(string key) => Resources.GetString(key, Culture) ?? key;')
[void] $cs.AppendLine('')
[void] $cs.AppendLine('    /// <summary>Formats a string that contains placeholders such as {0}.</summary>')
[void] $cs.AppendLine('    public string Format(string key, params object?[] args) => string.Format(Culture, Get(key), args);')
[void] $cs.AppendLine('')
[void] $cs.AppendLine('    /// <summary>Formats a count, using the "keyOne" variant for exactly one when it exists.</summary>')
[void] $cs.AppendLine('    public string Plural(string key, int count) =>')
[void] $cs.AppendLine('        count == 1 && Resources.GetString(key + "One", Culture) is not null ? Format(key + "One", count) : Format(key, count);')
[void] $cs.AppendLine('}')
[IO.File]::WriteAllText((Join-Path $dir 'LocalizedStrings.cs'), $cs.ToString().Replace("`r`n", "`n"), [Text.UTF8Encoding]::new($false))

Write-Host "Generated $($rows.Count) strings."
